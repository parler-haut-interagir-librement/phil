<?php

declare(strict_types=1);

namespace Phil\ContentBundle\Domain\Repository;

use Phil\ContentBundle\Domain\Content\ContentRoot;
use Phil\ContentBundle\Domain\Exception\InvalidContent;
use Phil\ContentBundle\Domain\ValueObject\ContentReference;

/**
 * Finds and stores content roots by their `ContentReference`, whatever the application's identifier type.
 * `Infrastructure\Doctrine\DoctrineContentRootRepository` is the Doctrine adapter.
 */
interface ContentRootRepository
{
    /**
     * The root `$reference` names, or `null` when none exists or the identifier cannot be one of its kind.
     */
    public function find(ContentReference $reference): ?ContentRoot;

    /**
     * Every root of one kind of content.
     *
     * @return list<ContentRoot>
     */
    public function findAll(string $resourceKey): array;

    /**
     * How `$root` is named outside the storage. A root whose identifier is generated by the database has a
     * reference only once it is flushed.
     *
     * @throws InvalidContent when the identifier has no string form a reference holds
     */
    public function referenceOf(ContentRoot $root): ContentReference;

    public function add(ContentRoot $root): void;

    /**
     * Deletes a stored root when the caller's transaction flushes. Its rows and routes are the caller's to
     * remove first (`ContentManager::delete()`).
     */
    public function remove(ContentRoot $root): void;
}
