<?php

declare(strict_types=1);

namespace Phil\Measurement\Tests\Unit\Cldr;

use JsonException;
use Phil\Measurement\Cldr\CldrImporter;
use Phil\Measurement\Exception\InvalidUnitDefinition;
use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;

#[CoversClass(CldrImporter::class)]
final class CldrImporterTest extends TestCase
{
    private string $directory;

    protected function setUp(): void
    {
        $this->directory = sys_get_temp_dir().'/phil-measurement-cldr-'.bin2hex(random_bytes(4));
    }

    protected function tearDown(): void
    {
        foreach ([...$this->files($this->directory.'/patterns/*'), ...$this->files($this->directory.'/*.php'), $this->directory.'/VERSION'] as $file) {
            if (is_file($file)) {
                unlink($file);
            }
        }

        foreach ([$this->directory.'/patterns', $this->directory] as $directory) {
            if (is_dir($directory)) {
                rmdir($directory);
            }
        }
    }

    public function testItWritesThePreferencesAndThePatternsItReads(): void
    {
        $count = new CldrImporter()->import($this->preferences(), ['fr-CA' => $this->units('fr-CA')], '49.0.0', $this->directory);

        self::assertSame(1, $count);
        self::assertSame("49.0.0\n", file_get_contents($this->directory.'/VERSION'));

        /** @var array<string, mixed> $preferences */
        $preferences = require $this->directory.'/preferences.php';
        self::assertSame([
            'length' => [
                'person-height' => ['US' => [['units' => ['length-foot', 'length-inch']]]],
                'road' => ['001' => [['units' => ['length-kilometer'], 'geq' => '0.9'], ['units' => ['length-meter'], 'geq' => '300'], ['units' => ['length-meter'], 'geq' => '2.5'], ['units' => ['length-meter']]]],
            ],
        ], $preferences);

        /** @var array<string, mixed> $patterns */
        $patterns = require $this->directory.'/patterns/fr_CA.php';
        self::assertSame([
            'long' => ['mass-kilogram' => ['name' => 'kilogrammes', 'one' => '{0} kilogramme', 'other' => "{0} kilogrammes l'été"]],
            'short' => ['mass-kilogram' => ['other' => '{0} kg']],
        ], $patterns);
        self::assertStringContainsString('The unit patterns of CLDR 49.0.0 for fr_CA, by width and unit. Generated by bin/import-cldr.php.', (string) file_get_contents($this->directory.'/patterns/fr_CA.php'));
    }

    public function testTheDirectoryMayAlreadyExist(): void
    {
        mkdir($this->directory.'/patterns', 0o755, true);

        self::assertSame(0, new CldrImporter()->import($this->preferences(), [], '49', $this->directory));
        self::assertFileExists($this->directory.'/preferences.php');
    }

    /**
     * @return iterable<string, array{string}>
     */
    public static function invalidVersions(): iterable
    {
        yield 'empty' => [''];
        yield 'word' => ['latest'];
        yield 'four parts' => ['49.0.0.1'];
        yield 'line break' => ["49\n"];
    }

    #[DataProvider('invalidVersions')]
    public function testItRefusesAnInvalidVersion(string $version): void
    {
        $this->expectException(InvalidUnitDefinition::class);
        $this->expectExceptionMessageIsOrContains('is not a CLDR version such as 49.0.0.');
        new CldrImporter()->import($this->preferences(), [], $version, $this->directory);
    }

    public function testItRefusesAnInvalidLocale(): void
    {
        $this->expectException(InvalidUnitDefinition::class);
        $this->expectExceptionMessageIsOrContains('"../fr" is not a CLDR locale.');
        new CldrImporter()->import($this->preferences(), ['../fr' => $this->units('../fr')], '49', $this->directory);
    }

    public function testItRefusesPreferencesWithoutTheirKey(): void
    {
        $this->expectException(InvalidUnitDefinition::class);
        $this->expectExceptionMessageIsOrContains('The unit preferences are read from supplemental.unitPreferenceData.');
        new CldrImporter()->preferences('{"supplemental": {}}');
    }

    public function testItRefusesPreferencesThatAreNotAnObject(): void
    {
        $this->expectException(InvalidUnitDefinition::class);
        new CldrImporter()->preferences('[1]');
    }

    public function testItRefusesACandidateWithoutItsUnit(): void
    {
        $this->expectException(InvalidUnitDefinition::class);
        $this->expectExceptionMessageIsOrContains('A unit preference of "mass" names its unit.');
        new CldrImporter()->preferences('{"supplemental": {"unitPreferenceData": {"mass": {"default": {"001": [{"unit": "Kilo Gram"}]}}}}}');
    }

    public function testItRefusesInvalidJson(): void
    {
        $this->expectException(JsonException::class);
        new CldrImporter()->preferences('{');
    }

    public function testItRefusesUnitsWithoutTheirKey(): void
    {
        $this->expectException(InvalidUnitDefinition::class);
        $this->expectExceptionMessageIsOrContains('The unit patterns of "fr" are read from main.fr.units.');
        new CldrImporter()->patterns('fr', '{"main": {"en": {"units": {}}}}');
    }

    public function testItSkipsWhatItDoesNotRead(): void
    {
        $json = '{"supplemental": {"unitPreferenceData": {"mass": "x", "area": {"default": "x", "floor": {"001": "x", "US": ["x"]}}, "concentr": {"default": {"001": [{"unit": "percent"}]}}}}}';

        self::assertSame([], new CldrImporter()->preferences('{"supplemental": {"unitPreferenceData": {"mass": "x", "area": {"default": "x", "floor": {"001": "x"}}}}}'));

        $this->expectException(InvalidUnitDefinition::class);
        new CldrImporter()->preferences($json);
    }

    public function testThePreferencesFileSaysWhichReleaseItHolds(): void
    {
        new CldrImporter()->import($this->preferences(), [], '49.0.0', $this->directory);

        self::assertStringContainsString("// The unit preferences of CLDR 49.0.0, by category, usage and region. Generated by bin/import-cldr.php.\nreturn ", (string) file_get_contents($this->directory.'/preferences.php'));
    }

    public function testEveryCategoryIsKept(): void
    {
        $json = '{"supplemental": {"unitPreferenceData": {"length": {"default": {"001": [{"unit": "meter"}]}}, "mass": {"default": {"001": [{"unit": "kilogram"}]}}}}}';

        self::assertSame([
            'length' => ['default' => ['001' => [['units' => ['length-meter']]]]],
            'mass' => ['default' => ['001' => [['units' => ['mass-kilogram']]]]],
        ], new CldrImporter()->preferences($json));
    }

    /**
     * @return iterable<string, array{string}>
     */
    public static function invalidLocales(): iterable
    {
        yield 'trailing symbol' => ['fr-CA!'];
        yield 'line break' => ["fr\n"];
    }

    #[DataProvider('invalidLocales')]
    public function testItRefusesALocaleWithATail(string $locale): void
    {
        $this->expectException(InvalidUnitDefinition::class);
        $this->expectExceptionMessageIsOrContains('is not a CLDR locale.');
        new CldrImporter()->import($this->preferences(), [$locale => $this->units($locale)], '49', $this->directory);
    }

    public function testItRefusesAUnitPreferenceWithALineBreak(): void
    {
        $this->expectException(InvalidUnitDefinition::class);
        new CldrImporter()->preferences('{"supplemental": {"unitPreferenceData": {"mass": {"default": {"001": [{"unit": "kilogram\n"}]}}}}}');
    }

    /**
     * @return iterable<string, array{mixed, ?string}>
     */
    public static function thresholds(): iterable
    {
        yield 'a decimal' => ['12.5', '12.5'];
        yield 'eighteen digits' => [str_repeat('9', 18), str_repeat('9', 18)];
        yield 'before the digits' => ['x1', null];
        yield 'after the digits' => ['1x', null];
        yield 'a line break' => ["1\n", null];
        yield 'a point without fraction' => ['1.', null];
        yield 'nineteen digits' => [str_repeat('9', 19), null];
        yield 'a float' => [0.9, '0.9'];
        yield 'ten fraction digits' => [1.0e-10, '0.0000000001'];
        yield 'below ten fraction digits' => [1.0e-11, '0'];
        yield 'an integer' => [300, '300'];
    }

    #[DataProvider('thresholds')]
    public function testAThresholdIsReadAsTheShortestDecimal(mixed $geq, ?string $expected): void
    {
        $json = json_encode(['supplemental' => ['unitPreferenceData' => ['mass' => ['default' => ['001' => [['unit' => 'kilogram', 'geq' => $geq]]]]]]], \JSON_THROW_ON_ERROR | \JSON_PRESERVE_ZERO_FRACTION);
        $candidate = new CldrImporter()->preferences($json)['mass']['default']['001'][0];

        self::assertSame(null === $expected ? ['units' => ['mass-kilogram']] : ['units' => ['mass-kilogram'], 'geq' => $expected], $candidate);
    }

    public function testNothingDeeperThanSixteenLevelsIsRead(): void
    {
        $preferences = static fn (int $depth): string => '{"supplemental": {"unitPreferenceData": {"mass": {"default": {"001": [{"unit": "kilogram", "x": '.str_repeat('[', $depth).str_repeat(']', $depth).'}]}}}}}';

        self::assertCount(1, new CldrImporter()->preferences($preferences(8)));

        try {
            new CldrImporter()->preferences($preferences(9));
            self::fail('A document of 17 levels is refused.');
        } catch (JsonException) {
            $patterns = static fn (int $depth): string => '{"main": {"fr": {"units": {"long": {"mass-kilogram": {"unitPattern-count-other": "{0} kg", "x": '.str_repeat('[', $depth).str_repeat(']', $depth).'}}}}}}';

            self::assertCount(1, new CldrImporter()->patterns('fr', $patterns(9)));

            $this->expectException(JsonException::class);
            new CldrImporter()->patterns('fr', $patterns(10));
        }
    }

    public function testTheNumberOfCharsBeforeTheCategoryDoesNotMatter(): void
    {
        $json = json_encode(['main' => ['fr' => ['units' => ['long' => [
            'mass-kilogram-extra-part' => ['unitPattern-count-other' => '{0} kg'],
            'mass-gram' => ['unitPattern-count-other' => '{0} g'],
        ]]]]], \JSON_THROW_ON_ERROR);

        self::assertSame(['long' => ['mass-kilogram-extra-part' => ['other' => '{0} kg'], 'mass-gram' => ['other' => '{0} g']]], new CldrImporter()->patterns('fr', $json));
    }

    public function testARegionOfDigitsOnlyIsNotWritten(): void
    {
        // PHP turns the key "840" into an integer, which the data files, strings only, do not hold.
        $this->expectException(InvalidUnitDefinition::class);
        $this->expectExceptionMessageIsOrContains('The CLDR data holds strings only.');
        new CldrImporter()->import('{"supplemental": {"unitPreferenceData": {"mass": {"default": {"840": [{"unit": "kilogram"}]}}}}}', [], '49', $this->directory);
    }

    public function testTheDirectoriesAreMadeReadableByEveryone(): void
    {
        $umask = umask(0);

        try {
            new CldrImporter()->import($this->preferences(), ['fr' => $this->units('fr')], '49', $this->directory);
        } finally {
            umask($umask);
        }

        self::assertSame(0o755, fileperms($this->directory) & 0o777);
        self::assertSame(0o755, fileperms($this->directory.'/patterns') & 0o777);
    }

    /**
     * @return list<string>
     */
    private function files(string $pattern): array
    {
        $files = glob($pattern);

        return false === $files ? [] : $files;
    }

    private function preferences(): string
    {
        return json_encode(['supplemental' => ['unitPreferenceData' => [
            'length' => [
                'person-height' => ['US' => [['unit' => 'foot-and-inch']]],
                'road' => ['001' => [['unit' => 'kilometer', 'geq' => 0.9], ['unit' => 'meter', 'geq' => 300], ['unit' => 'meter', 'geq' => '2.5'], ['unit' => 'meter', 'geq' => 'many']]],
            ],
            'concentr' => ['default' => ['001' => [['unit' => 'percent']]]],
        ]]], \JSON_THROW_ON_ERROR);
    }

    private function units(string $locale): string
    {
        return json_encode(['main' => [$locale => ['units' => [
            'long' => [
                'mass-kilogram' => ['displayName' => 'kilogrammes', 'unitPattern-count-one' => '{0} kilogramme', 'unitPattern-count-other' => "{0} kilogrammes l'été", 'unitPattern-count-many' => 'sans marque'],
                'mass-gram' => ['displayName' => 'grammes'],
                'per' => ['compoundUnitPattern' => '{0} par {1}'],
                'digital-byte' => ['unitPattern-count-other' => '{0} octets'],
            ],
            'short' => ['mass-kilogram' => ['displayName' => 7, 'unitPattern-count-other' => '{0} kg']],
            'narrow' => 'x',
        ]]]], \JSON_THROW_ON_ERROR);
    }
}
