<?php

declare(strict_types=1);

namespace Phil\EmailAddress\Internal;

use Phil\EmailAddress\Exception\InvalidDomainList;
use Symfony\Component\Filesystem\Exception\IOException;
use Symfony\Component\Filesystem\Filesystem;

/**
 * The `data/` directory of the library: one PHP file per list, and `VERSION`, one line per list naming its file, its
 * source and the release imported. Each file is written by `Filesystem::dumpFile()`, beside its place and then moved
 * there, so that no reader ever sees half a file.
 *
 * @internal
 */
final readonly class DataDirectory
{
    public const string VERSION_FILE = 'VERSION';

    public function __construct(
        private string $path,
        private Filesystem $filesystem = new Filesystem(),
    ) {
    }

    /**
     * Refuses a release or a source that would not fit on its line of `VERSION`.
     *
     * @throws InvalidDomainList
     */
    public static function checkWord(string $word): void
    {
        if (1 !== preg_match('/^[\x21-\x7E]+$/', $word)) {
            throw InvalidDomainList::notAWord($word);
        }
    }

    /**
     * Writes a list of checked ASCII names, which hold only letters, digits, dots and hyphens: nothing to escape.
     *
     * @param list<string> $names
     *
     * @throws InvalidDomainList when the directory is missing or the file cannot be written
     */
    public function writeList(string $file, string $importer, array $names): void
    {
        $php = "<?php\n\ndeclare(strict_types=1);\n\n// Generated by ".$importer." from the release named in VERSION: import a\n// newer release rather than editing this file.\n\nreturn [\n";

        foreach ($names as $name) {
            $php .= "    '".$name."',\n";
        }

        $this->dump($file, $php."];\n");
    }

    /**
     * Names the source and release of one list in `VERSION`, keeping the lines of the other lists.
     *
     * @throws InvalidDomainList when the directory is missing or the file cannot be written
     */
    public function recordRelease(string $file, string $source, string $release): void
    {
        $lines = [];
        $current = is_file($this->path.'/'.self::VERSION_FILE) ? (string) file_get_contents($this->path.'/'.self::VERSION_FILE) : '';

        foreach (explode("\n", $current) as $line) {
            $name = strtok($line, ' ');

            if (\is_string($name) && '' !== trim($line)) {
                $lines[$name] = $line;
            }
        }

        $lines[$file] = $file.' '.$source.' '.$release;
        ksort($lines, \SORT_STRING);

        $this->dump(self::VERSION_FILE, implode("\n", $lines)."\n");
    }

    private function dump(string $file, string $content): void
    {
        $target = $this->path.'/'.$file;

        // dumpFile() would create a missing directory: a mistyped path is refused instead.
        if (!is_dir($this->path)) {
            throw InvalidDomainList::unwritable($target);
        }

        try {
            $this->filesystem->dumpFile($target, $content);
        } catch (IOException) {
            throw InvalidDomainList::unwritable($target);
        }
    }
}
