<?php

declare(strict_types=1);

namespace Phil\EmailAddress\Tests\Unit\Data;

use Phil\EmailAddress\Data\DisposableDomainsImporter;
use Phil\EmailAddress\Exception\InvalidDomainList;
use Phil\EmailAddress\Internal\DataDirectory;
use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;

#[CoversClass(DisposableDomainsImporter::class)]
#[CoversClass(DataDirectory::class)]
#[CoversClass(InvalidDomainList::class)]
final class DisposableDomainsImporterTest extends TestCase
{
    private string $directory;

    protected function setUp(): void
    {
        $this->directory = sys_get_temp_dir().'/phil-email-address-'.bin2hex(random_bytes(6));
        mkdir($this->directory);
    }

    protected function tearDown(): void
    {
        foreach ($this->files() as $file) {
            is_dir($file) ? rmdir($file) : unlink($file);
        }

        rmdir($this->directory);
    }

    /**
     * @return list<string>
     */
    private function files(): array
    {
        $files = glob($this->directory.'/*');

        return false === $files ? [] : $files;
    }

    public function testWritesTheDomainsCheckedSortedAndOnce(): void
    {
        $list = "# disposable domains\r\nZeta.example\n\n  alpha.example  # first # and more\nbücher.example\nzeta.example\n";

        $count = new DisposableDomainsImporter()->import($list, $this->directory, 'v1', 'https://example.org/list');

        self::assertSame(3, $count);
        self::assertSame(['alpha.example', 'xn--bcher-kva.example', 'zeta.example'], require $this->directory.'/disposable-domains.php');
        self::assertSame(
            "<?php\n\ndeclare(strict_types=1);\n\n// Generated by Phil\\EmailAddress\\Data\\DisposableDomainsImporter from the release named in VERSION: import a\n// newer release rather than editing this file.\n\nreturn [\n    'alpha.example',\n    'xn--bcher-kva.example',\n    'zeta.example',\n];\n",
            file_get_contents($this->directory.'/disposable-domains.php'),
        );
        self::assertSame("disposable-domains.php https://example.org/list v1\n", file_get_contents($this->directory.'/VERSION'));
        self::assertSame(['VERSION', 'disposable-domains.php'], array_map(basename(...), $this->files()));
    }

    public function testNamesTheSourceOfTheListByDefault(): void
    {
        new DisposableDomainsImporter()->import('a.example', $this->directory, '2026-11-11');

        self::assertSame("disposable-domains.php https://github.com/disposable-email-domains/disposable-email-domains 2026-11-11\n", file_get_contents($this->directory.'/VERSION'));
    }

    public function testKeepsTheReleasesOfTheOtherLists(): void
    {
        file_put_contents($this->directory.'/VERSION', "top-level-domains.php https://example.org/tlds 2026111000\n\ndisposable-domains.php https://example.org/old v0\n");

        new DisposableDomainsImporter()->import('a.example', $this->directory, 'v2', 'https://example.org/list');

        self::assertSame(
            "disposable-domains.php https://example.org/list v2\ntop-level-domains.php https://example.org/tlds 2026111000\n",
            file_get_contents($this->directory.'/VERSION'),
        );
    }

    public function testWritesAnEmptyList(): void
    {
        self::assertSame(0, new DisposableDomainsImporter()->import("# nothing\n", $this->directory, 'v1'));
        self::assertSame([], require $this->directory.'/disposable-domains.php');
    }

    public function testWritesNothingWhenALineIsNotADomain(): void
    {
        try {
            new DisposableDomainsImporter()->import("a.example\n\nlocalhost\n", $this->directory, 'v1');
            self::fail('The list was imported.');
        } catch (InvalidDomainList $invalidDomainList) {
            self::assertSame('Line 3 of the domain list is not a domain: the domain has no dot.', $invalidDomainList->getMessage());
        }

        self::assertSame([], $this->files());
    }

    /**
     * @return iterable<string, array{string, string, string}>
     */
    public static function badWords(): iterable
    {
        yield 'a space in the release' => ['v 1', 'x', '"v 1" must be printable ASCII without spaces, to fit on its line of VERSION.'];
        yield 'an empty release' => ['', 'x', '"" must be printable ASCII without spaces, to fit on its line of VERSION.'];
        yield 'a line break in the source' => ['v1', "x\ny", '"x\\ny" must be printable ASCII without spaces, to fit on its line of VERSION.'];
        yield 'a letter outside ASCII' => ['vé', 'x', '"v\\303\\251" must be printable ASCII without spaces, to fit on its line of VERSION.'];
    }

    #[DataProvider('badWords')]
    public function testRefusesAReleaseOrSourceThatDoesNotFitOnALine(string $release, string $source, string $message): void
    {
        try {
            new DisposableDomainsImporter()->import('a.example', $this->directory, $release, $source);
            self::fail('The list was imported.');
        } catch (InvalidDomainList $invalidDomainList) {
            self::assertSame($message, $invalidDomainList->getMessage());
        }

        self::assertSame([], $this->files());
    }

    public function testReportsADirectoryThatDoesNotExist(): void
    {
        $this->expectExceptionObject(InvalidDomainList::unwritable($this->directory.'/missing/disposable-domains.php'));

        try {
            new DisposableDomainsImporter()->import('a.example', $this->directory.'/missing', 'v1');
        } finally {
            self::assertDirectoryDoesNotExist($this->directory.'/missing');
        }
    }

    public function testReportsAFileThatCannotBeReplaced(): void
    {
        mkdir($this->directory.'/VERSION');

        try {
            new DisposableDomainsImporter()->import('a.example', $this->directory, 'v1');
            self::fail('The list was imported.');
        } catch (InvalidDomainList $invalidDomainList) {
            self::assertSame(InvalidDomainList::unwritable($this->directory.'/VERSION')->getMessage(), $invalidDomainList->getMessage());
        }

        self::assertSame(['VERSION', 'disposable-domains.php'], array_map(basename(...), $this->files()));
    }
}
