<?php

declare(strict_types=1);

namespace Phil\EmailAddress\Tests\Unit\Data;

use Phil\EmailAddress\Data\TopLevelDomainsImporter;
use Phil\EmailAddress\Exception\InvalidDomainList;
use Phil\EmailAddress\Internal\DataDirectory;
use Phil\EmailAddress\Internal\TopLevelLabel;
use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;

#[CoversClass(TopLevelDomainsImporter::class)]
#[CoversClass(TopLevelLabel::class)]
#[CoversClass(DataDirectory::class)]
#[CoversClass(InvalidDomainList::class)]
final class TopLevelDomainsImporterTest extends TestCase
{
    /** A made-up extract in the shape of the IANA file. */
    private const string LIST = "# Version 2026111000, Last Updated Tue Nov 11 07:07:01 2026 UTC\nCOM\nCA\r\nXN--P1AI\n\nAAA\nca\n";

    private string $directory;

    protected function setUp(): void
    {
        $this->directory = sys_get_temp_dir().'/phil-email-address-'.bin2hex(random_bytes(6));
        mkdir($this->directory);
    }

    protected function tearDown(): void
    {
        foreach ($this->files() as $file) {
            unlink($file);
        }

        rmdir($this->directory);
    }

    /**
     * @return list<string>
     */
    private function files(): array
    {
        $files = glob($this->directory.'/*');

        return false === $files ? [] : $files;
    }

    public function testWritesTheDomainsInLowercaseSortedAndOnce(): void
    {
        $count = new TopLevelDomainsImporter()->import(self::LIST, $this->directory);

        self::assertSame(4, $count);
        self::assertSame(['aaa', 'ca', 'com', 'xn--p1ai'], require $this->directory.'/top-level-domains.php');
        self::assertStringContainsString('// Generated by Phil\\EmailAddress\\Data\\TopLevelDomainsImporter from', (string) file_get_contents($this->directory.'/top-level-domains.php'));
        self::assertSame("top-level-domains.php https://data.iana.org/TLD/tlds-alpha-by-domain.txt 2026111000\n", file_get_contents($this->directory.'/VERSION'));
    }

    public function testReadsTheReleaseOfTheFirstVersionLineOnly(): void
    {
        new TopLevelDomainsImporter()->import("# comment\n#Version 2026010100\n# Version 2026020200\nCOM\n", $this->directory, 'https://example.org/tlds');

        self::assertSame("top-level-domains.php https://example.org/tlds 2026010100\n", file_get_contents($this->directory.'/VERSION'));
    }

    public function testRefusesAListWithoutItsVersionLine(): void
    {
        try {
            new TopLevelDomainsImporter()->import("# Version 12345\nCOM\n", $this->directory);
            self::fail('The list was imported.');
        } catch (InvalidDomainList $invalidDomainList) {
            self::assertSame('The list does not start with the "# Version" line that names its release.', $invalidDomainList->getMessage());
        }

        self::assertSame([], $this->files());
    }

    public function testRefusesAVersionThatDoesNotStartItsComment(): void
    {
        $this->expectExceptionObject(InvalidDomainList::noRelease());

        new TopLevelDomainsImporter()->import("# Copied from # Version 2026111000\nCOM\n", $this->directory);
    }

    public function testKeepsTheOtherListsOfVersionAndDropsItsBlankLines(): void
    {
        file_put_contents($this->directory.'/VERSION', "\t\nother.php https://example.org/other 1\n  \n\n");

        new TopLevelDomainsImporter()->import(self::LIST, $this->directory);

        self::assertSame("other.php https://example.org/other 1\ntop-level-domains.php https://data.iana.org/TLD/tlds-alpha-by-domain.txt 2026111000\n", file_get_contents($this->directory.'/VERSION'));
    }

    public function testRefusesASourceThatDoesNotFitOnALine(): void
    {
        $this->expectExceptionObject(InvalidDomainList::notAWord('a b'));

        new TopLevelDomainsImporter()->import(self::LIST, $this->directory, 'a b');
    }

    /**
     * @return iterable<string, array{string}>
     */
    public static function badLabels(): iterable
    {
        yield 'one letter' => ['C'];
        yield 'digits' => ['123'];
        yield 'a digit among letters' => ['C0M'];
        yield 'a hyphen' => ['CO-M'];
        yield 'a dot' => ['CO.UK'];
        yield 'a label too long' => [str_repeat('A', 64)];
        yield 'an A-label that does not decode' => ['XN--ZZZZZZ'];
        yield 'an A-label ending with a hyphen' => ['XN--P1AI-'];
        yield 'an empty A-label' => ['XN--'];
        yield 'a Unicode label' => ['РФ'];
        yield 'an A-label after other characters' => ['A1XN--P1AI'];
        // "aא": a Latin letter beside a Hebrew one, refused by the bidi rule.
        yield 'an A-label that mixes directions' => ['XN--A-0HC'];
        // "a" ZWNJ "b": a joiner with no virama before it, refused by the CONTEXTJ rule.
        yield 'an A-label with a stray joiner' => ['XN--AB-J1T'];
    }

    #[DataProvider('badLabels')]
    public function testWritesNothingWhenALineIsNotATopLevelDomain(string $label): void
    {
        try {
            new TopLevelDomainsImporter()->import("# Version 2026111000\nCOM\n".$label."\n", $this->directory);
            self::fail('The list was imported.');
        } catch (InvalidDomainList $invalidDomainList) {
            self::assertSame('Line 3 of the domain list is not a domain: the top-level domain is numeric or a single letter.', $invalidDomainList->getMessage());
        }

        self::assertSame([], $this->files());
    }

    public function testAcceptsTheLongestLabels(): void
    {
        $letters = str_repeat('a', 63);
        // The A-label of 55 letters "a" and an "é": 63 octets.
        $aLabel = 'xn--'.str_repeat('a', 55).'-u3e';

        self::assertSame($letters, TopLevelLabel::normalize(strtoupper($letters)));
        self::assertSame($aLabel, TopLevelLabel::normalize($aLabel));
        self::assertNull(TopLevelLabel::normalize('xn--'.str_repeat('a', 56).'-u3e'));
        self::assertSame('xn--p1ai', TopLevelLabel::normalize('xn--p1ai'));
        self::assertSame('xn--vermgensberatung-pwb', TopLevelLabel::normalize('XN--VERMGENSBERATUNG-PWB'));
    }
}
