<?php

declare(strict_types=1);

namespace Phil\DddBundle\Domain\Identifier;

use Phil\DddBundle\Domain\Exception\InvalidValue;
use Stringable;
use Symfony\Component\Uid\Uuid;
use Symfony\Component\Uid\UuidV7;

/**
 * Base of every aggregate identifier.
 *
 * UUIDv7: time-ordered, so a B-tree insert does not fragment the index the way v4 does, and an identifier
 * carries its own creation date. `symfony/uid` is a library of value types with no container and no I/O,
 * which is why a `Domain` may depend on it.
 *
 * **This is the internal representation, and nothing more.** An identifier that leaves the system — in a
 * token, a public URL, an export — has a presentation the application decides; this class does not decide
 * it, and no presentation method will be added to it.
 */
abstract readonly class Identifier implements Stringable
{
    final private function __construct(
        public UuidV7 $value,
    ) {
    }

    /**
     * Identifiers are generated by the caller, not by the database — that is what lets a command return
     * `void`.
     */
    public static function generate(): static
    {
        return new static(Uuid::v7());
    }

    public static function fromString(string $value): static
    {
        if (!Uuid::isValid($value)) {
            throw InvalidValue::because(\sprintf('"%s" is not a UUID.', $value));
        }

        return static::fromUuid(Uuid::fromString($value));
    }

    /**
     * From a UUID already parsed — read from sixteen bytes, say —, without printing and parsing it again.
     */
    public static function fromUuid(Uuid $uuid): static
    {
        if (!$uuid instanceof UuidV7) {
            throw InvalidValue::because(\sprintf('"%s" is a UUID, but not a v7.', $uuid->toRfc4122()));
        }

        return new static($uuid);
    }

    public function equals(self $other): bool
    {
        return static::class === $other::class && $this->value->equals($other->value);
    }

    public function toString(): string
    {
        return $this->value->toRfc4122();
    }

    public function __toString(): string
    {
        return $this->toString();
    }
}
