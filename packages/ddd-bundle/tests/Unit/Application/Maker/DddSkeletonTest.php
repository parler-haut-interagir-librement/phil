<?php

declare(strict_types=1);

namespace Phil\DddBundle\Tests\Unit\Application\Maker;

use InvalidArgumentException;
use Phil\DddBundle\Application\Maker\DddSkeleton;
use Phil\DddBundle\Application\Maker\SkeletonFile;
use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;

#[CoversClass(DddSkeleton::class)]
#[CoversClass(SkeletonFile::class)]
final class DddSkeletonTest extends TestCase
{
    public function testAContextIsItsThreeLayersAndItsReadme(): void
    {
        $files = new DddSkeleton()->context('Catalog');

        self::assertSame(
            ['src/Catalog/README.md', 'src/Catalog/Domain/.gitignore', 'src/Catalog/Application/.gitignore', 'src/Catalog/Infrastructure/.gitignore'],
            array_map(static fn (SkeletonFile $file): string => $file->path, $files),
        );
        self::assertStringStartsWith("# Catalog\n\nThe bounded context Catalog: ", $files[0]->contents);
        self::assertStringContainsString('| `Domain` | `App\Catalog\Domain` |', $files[0]->contents);
        self::assertStringContainsString('| `Infrastructure` | `App\Catalog\Infrastructure` |', $files[0]->contents);
        self::assertStringNotContainsString('{{', $files[0]->contents);
        self::assertSame('', $files[1]->contents);
        self::assertSame('', $files[2]->contents);
        self::assertSame('', $files[3]->contents);
    }

    public function testAnIdentifierIsItsClassAndItsType(): void
    {
        $files = new DddSkeleton()->identifier('Catalog', 'Product');

        self::assertCount(2, $files);
        self::assertSame('src/Catalog/Domain/ProductId.php', $files[0]->path);
        self::assertSame(<<<'PHP'
            <?php

            declare(strict_types=1);

            namespace App\Catalog\Domain;

            use Phil\DddBundle\Domain\Identifier\Identifier;

            /**
             * The identifier of the product aggregate: a UUIDv7, generated by the caller with ProductId::generate().
             */
            final readonly class ProductId extends Identifier
            {
            }

            PHP, $files[0]->contents);
        self::assertSame('src/Catalog/Infrastructure/Persistence/Doctrine/Type/ProductIdType.php', $files[1]->path);
        self::assertSame(<<<'PHP'
            <?php

            declare(strict_types=1);

            namespace App\Catalog\Infrastructure\Persistence\Doctrine\Type;

            use App\Catalog\Domain\ProductId;
            use Override;
            use Phil\DddBundle\Infrastructure\Doctrine\IdentifierType;

            /**
             * The DBAL type of ProductId, registered as "product_id" in config/packages/doctrine.php.
             *
             * @extends IdentifierType<ProductId>
             */
            final class ProductIdType extends IdentifierType
            {
                #[Override]
                protected function identifierClass(): string
                {
                    return ProductId::class;
                }
            }

            PHP, $files[1]->contents);
    }

    public function testTheIdSuffixIsNotRepeated(): void
    {
        $skeleton = new DddSkeleton();

        self::assertSame('src/Catalog/Domain/ProductId.php', $skeleton->identifier('Catalog', 'ProductId')[0]->path);
        self::assertSame('src/Catalog/Domain/IdId.php', $skeleton->identifier('Catalog', 'Id')[0]->path);
        self::assertSame('product_id', $skeleton->typeName('ProductId'));
        self::assertSame('product_id', $skeleton->typeName('Product'));
        self::assertSame('html_page_id', $skeleton->typeName('HTMLPage'));
        self::assertSame('order2_line_id', $skeleton->typeName('Order2Line'));
        self::assertSame('App\Catalog\Infrastructure\Persistence\Doctrine\Type\ProductIdType', $skeleton->typeClass('Catalog', 'ProductId'));
    }

    public function testTheImportsAreSortedWhateverTheRootNamespace(): void
    {
        $files = new DddSkeleton('Zoo', 'app')->identifier('Animals', 'Lion');

        self::assertSame('app/Animals/Infrastructure/Persistence/Doctrine/Type/LionIdType.php', $files[1]->path);
        self::assertStringContainsString(
            "use Override;\nuse Phil\\DddBundle\\Infrastructure\\Doctrine\\IdentifierType;\nuse Zoo\\Animals\\Domain\\LionId;\n",
            $files[1]->contents,
        );
    }

    public function testACommandIsItsMessageAndItsHandler(): void
    {
        $files = new DddSkeleton()->command('Catalog', 'AddProduct');

        self::assertCount(2, $files);
        self::assertSame('src/Catalog/Application/AddProductCommand.php', $files[0]->path);
        self::assertSame(<<<'PHP'
            <?php

            declare(strict_types=1);

            namespace App\Catalog\Application;

            use Phil\DddBundle\Application\Bus\Command;

            /**
             * Add product, through the command bus. A command carries identifiers and scalars only, and returns nothing.
             *
             * @see AddProductHandler
             */
            final readonly class AddProductCommand implements Command
            {
            }

            PHP, $files[0]->contents);
        self::assertSame('src/Catalog/Application/AddProductHandler.php', $files[1]->path);
        self::assertSame(<<<'PHP'
            <?php

            declare(strict_types=1);

            namespace App\Catalog\Application;

            use Phil\DddBundle\Application\Bus\CommandHandler;

            /**
             * Handles AddProductCommand, in the transaction of the command bus.
             */
            final readonly class AddProductHandler implements CommandHandler
            {
                public function __invoke(AddProductCommand $command): void
                {
                }
            }

            PHP, $files[1]->contents);
    }

    public function testAQueryIsItsMessageAndItsHandler(): void
    {
        $files = new DddSkeleton()->query('Catalog', 'FindProductQuery');

        self::assertSame('src/Catalog/Application/FindProductQuery.php', $files[0]->path);
        self::assertSame(<<<'PHP'
            <?php

            declare(strict_types=1);

            namespace App\Catalog\Application;

            use Phil\DddBundle\Application\Bus\Query;

            /**
             * Find product, through the query bus. Replace null by the type of the answer, here and in the handler.
             *
             * @see FindProductHandler
             *
             * @implements Query<null>
             */
            final readonly class FindProductQuery implements Query
            {
            }

            PHP, $files[0]->contents);
        self::assertSame('src/Catalog/Application/FindProductHandler.php', $files[1]->path);
        self::assertSame(<<<'PHP'
            <?php

            declare(strict_types=1);

            namespace App\Catalog\Application;

            use Phil\DddBundle\Application\Bus\QueryHandler;

            /**
             * Answers FindProductQuery: reads the answer, a DTO, without loading an aggregate.
             */
            final readonly class FindProductHandler implements QueryHandler
            {
                public function __invoke(FindProductQuery $query): null
                {
                    return null;
                }
            }

            PHP, $files[1]->contents);
    }

    public function testAnEventIsADomainEventInTheEventFolder(): void
    {
        $files = new DddSkeleton()->event('Catalog', 'ProductAdded');

        self::assertCount(1, $files);
        self::assertSame('src/Catalog/Domain/Event/ProductAdded.php', $files[0]->path);
        self::assertSame(<<<'PHP'
            <?php

            declare(strict_types=1);

            namespace App\Catalog\Domain\Event;

            use DateTimeImmutable;
            use Phil\DddBundle\Domain\Event\DomainEvent;

            /**
             * Product added: a fact of the context Catalog, in the past.
             */
            final readonly class ProductAdded implements DomainEvent
            {
                public function __construct(
                    private DateTimeImmutable $occurredAt,
                ) {
                }

                public function occurredAt(): DateTimeImmutable
                {
                    return $this->occurredAt;
                }
            }

            PHP, $files[0]->contents);
    }

    /**
     * The suffix alone is a name: `Command` gives `CommandCommand`, not an empty class name.
     */
    public function testASuffixAloneIsKept(): void
    {
        $skeleton = new DddSkeleton();

        self::assertSame('src/Catalog/Application/CommandCommand.php', $skeleton->command('Catalog', 'Command')[0]->path);
        self::assertSame('src/Catalog/Application/QueryHandler.php', $skeleton->query('Catalog', 'Query')[1]->path);
    }

    /**
     * Every file written is PHP that parses, whatever the names.
     */
    public function testEveryPhpFileParses(): void
    {
        $skeleton = new DddSkeleton();
        $files = [
            ...$skeleton->identifier('Billing', 'Invoice'),
            ...$skeleton->command('Billing', 'SendInvoice'),
            ...$skeleton->query('Billing', 'CountInvoices'),
            ...$skeleton->event('Billing', 'InvoiceSent'),
        ];

        foreach ($files as $file) {
            self::assertStringEndsWith('.php', $file->path);
            self::assertNotSame([], token_get_all($file->contents, \TOKEN_PARSE), $file->path);
            self::assertStringNotContainsString('{{', $file->contents, $file->path);
        }
    }

    /**
     * @return iterable<string, array{string, string, string}>
     */
    public static function refusedNames(): iterable
    {
        yield 'lower-case context' => ['catalog', 'Product', 'The context name "catalog" is not a PascalCase word: a capital letter, then letters and digits.'];
        yield 'empty context' => ['', 'Product', 'The context name "" is not a PascalCase word'];
        yield 'namespace in the context' => ['Catalog\Admin', 'Product', 'The context name "Catalog\Admin"'];
        yield 'path in the name' => ['Catalog', '../Product', 'The class name "../Product"'];
        yield 'space in the name' => ['Catalog', 'Add product', 'The class name "Add product"'];
        yield 'empty name' => ['Catalog', '', 'The class name ""'];
        yield 'trailing new line' => ['Catalog', "Product\n", 'The class name "Product'];
        yield 'leading digit' => ['Catalog', '2Product', 'The class name "2Product"'];
    }

    #[DataProvider('refusedNames')]
    public function testABadNameIsRefused(string $context, string $name, string $message): void
    {
        $this->expectException(InvalidArgumentException::class);
        $this->expectExceptionMessageIsOrContains($message);

        new DddSkeleton()->command($context, $name);
    }

    public function testABadContextNameIsRefusedByEveryCommand(): void
    {
        $skeleton = new DddSkeleton();

        foreach ([
            static fn (): array => $skeleton->context('catalog'),
            static fn (): array => $skeleton->identifier('catalog', 'Product'),
            static fn (): array => $skeleton->query('catalog', 'FindProduct'),
            static fn (): array => $skeleton->event('catalog', 'ProductAdded'),
            static fn (): string => $skeleton->typeClass('catalog', 'Product'),
        ] as $call) {
            try {
                $call();
                self::fail('A lower-case context was accepted.');
            } catch (InvalidArgumentException $invalidArgumentException) {
                self::assertStringStartsWith('The context name "catalog"', $invalidArgumentException->getMessage());
            }
        }
    }

    public function testABadEventNameIsRefused(): void
    {
        $this->expectException(InvalidArgumentException::class);
        $this->expectExceptionMessageIsOrContains('The event name "productAdded"');

        new DddSkeleton()->event('Catalog', 'productAdded');
    }

    public function testAReservedWordCannotNameAClass(): void
    {
        $skeleton = new DddSkeleton();

        try {
            $skeleton->event('Catalog', 'List');
            self::fail('"List" named a class.');
        } catch (InvalidArgumentException $invalidArgumentException) {
            self::assertSame('"List" is a word PHP reserves: it cannot name a class.', $invalidArgumentException->getMessage());
        }

        // A reserved word is a fine context: PHP accepts it as a namespace segment.
        self::assertSame('src/List/Domain/Event/ItemAdded.php', $skeleton->event('List', 'ItemAdded')[0]->path);
        self::assertSame('src/Readonly/Domain/.gitignore', $skeleton->context('Readonly')[1]->path);
    }

    public function testAMissingTemplateIsRefused(): void
    {
        $this->expectException(InvalidArgumentException::class);
        $this->expectExceptionMessageIsOrContains('The template "DomainEvent.php.tpl" cannot be read.');

        new DddSkeleton(templates: __DIR__.'/missing')->event('Catalog', 'ProductAdded');
    }
}
