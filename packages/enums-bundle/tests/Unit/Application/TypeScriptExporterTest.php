<?php

declare(strict_types=1);

namespace Phil\EnumsBundle\Tests\Unit\Application;

use LogicException;
use Phil\EnumsBundle\Application\TypeScript\TypeScriptExporter;
use Phil\EnumsBundle\Tests\Unit\Finder\Ghost;
use Phil\EnumsBundle\Tests\Unit\Fixture\Access;
use Phil\EnumsBundle\Tests\Unit\Fixture\OrderStatus;
use Phil\EnumsBundle\Tests\Unit\Fixture\Shape;
use Phil\EnumsBundle\Tests\Unit\Fixture\TicketKind;
use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\TestCase;
use UnitEnum;

#[CoversClass(TypeScriptExporter::class)]
final class TypeScriptExporterTest extends TestCase
{
    public function testEachEnumBecomesAConstantAUnionTypeAndItsLabels(): void
    {
        self::assertSame(<<<'TS'
            // Generated by phil/enums-bundle; do not edit.

            export const Access = {
              Read: 1,
              Write: 2,
              /** @deprecated */
              Admin: 4,
            } as const;
            export type Access = (typeof Access)[keyof typeof Access];
            export const AccessLabels: Record<Access, string> = {
              1: "Read",
              2: "Write",
              4: "Admin",
            };
            export const AccessDescriptions: Partial<Record<Access, string>> = {
              4: "Every right.",
            };
            export const AccessGroups: Record<string, readonly Access[]> = {
              "basic": [1, 2],
              "editor": [2],
            };
            export const AccessDefault: Access = 1;

            export const Shape = {
              Circle: "Circle",
              BigSquare: "BigSquare",
              Blank: "Blank",
              Éclair: "Éclair",
            } as const;
            export type Shape = (typeof Shape)[keyof typeof Shape];
            export const ShapeLabels: Record<Shape, string> = {
              "Circle": "Round",
              "BigSquare": "BigSquare",
              "Blank": "Blank",
              "Éclair": "Éclair",
            };

            TS, TypeScriptExporter::export([Access::class, Shape::class]));
    }

    public function testTheLabelsComeFromTheCallbackWhenOneIsGiven(): void
    {
        $source = TypeScriptExporter::export([TicketKind::class], static fn (UnitEnum $case): string => 'label of '.$case->name);

        self::assertStringContainsString("  1: \"label of BugReport\",\n  2: \"label of FEATURE_REQUEST\",\n", $source);
    }

    public function testTheDescriptionsOfAStringEnumAreKeyedByValue(): void
    {
        self::assertStringContainsString("export const OrderStatusDescriptions: Partial<Record<OrderStatus, string>> = {\n  \"pending\": \"Waiting for payment.\",\n  \"in_transit\": \"The parcel has left.\",\n};\n", TypeScriptExporter::export([OrderStatus::class]));
        self::assertStringNotContainsString('OrderStatusDefault', TypeScriptExporter::export([OrderStatus::class]));
        self::assertStringContainsString("export const OrderStatusGroups: Record<string, readonly OrderStatus[]> = {\n  \"customer\": [\"pending\", \"in_transit\"],\n  \"staff\": [\"pending\", \"cancelled\"],\n};\n", TypeScriptExporter::export([OrderStatus::class]));
    }

    public function testNothingToExportIsOnlyTheHeader(): void
    {
        self::assertSame("// Generated by phil/enums-bundle; do not edit.\n", TypeScriptExporter::export([]));
    }

    public function testTwoEnumsOfOneShortNameAreRefused(): void
    {
        $this->expectException(LogicException::class);
        $this->expectExceptionMessageIsOrContains('Several enums are named Ghost; export them separately.');

        TypeScriptExporter::export([Ghost::class, Access::class, Ghost::class]);
    }

    public function testValuesAreWrittenAsJsonWithoutEscapingSlashesOrUnicode(): void
    {
        self::assertStringContainsString('"Éclair": "Éclair"', TypeScriptExporter::export([Shape::class]));
        self::assertStringContainsString('"a/b"', TypeScriptExporter::export([Ghost::class], static fn (): string => 'a/b'));
    }
}
