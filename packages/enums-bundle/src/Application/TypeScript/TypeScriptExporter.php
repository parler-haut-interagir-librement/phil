<?php

declare(strict_types=1);

namespace Phil\EnumsBundle\Application\TypeScript;

use BackedEnum;
use LogicException;
use Phil\Enums\Attribute\Group;
use Phil\Enums\Collection\CaseCollection;
use Phil\Enums\Meta\Reflection;
use Phil\EnumsBundle\Application\Translation\EnumTranslation;
use UnitEnum;

/**
 * Enums written as TypeScript, so that a front end shares their values and labels instead of copying them:
 *
 * ```ts
 * export const OrderStatus = {
 *   PENDING: "pending",
 * } as const;
 * export type OrderStatus = (typeof OrderStatus)[keyof typeof OrderStatus];
 * export const OrderStatusLabels: Record<OrderStatus, string> = {
 *   "pending": "Pending",
 * };
 * ```
 *
 * - **One constant object and one union type per enum**, named after the enum's short name; two enums of the same
 *   short name are refused rather than overwriting each other.
 * - **The labels** are what the callback gives, each case's `Label` — or its name — by default; the command passes
 *   one that translates.
 * - **Deprecated cases are kept**, with a `@deprecated` comment: the front end still reads the records that hold
 *   them.
 * - **What the enum declares beside** is written when it has some: `<Enum>Descriptions` for the cases with a
 *   `Description`, `<Enum>Groups` for its `#[Group]`s, `<Enum>Default` for its `#[DefaultCase]`.
 */
final class TypeScriptExporter
{
    private function __construct()
    {
    }

    /**
     * @param list<class-string<UnitEnum>>      $enums
     * @param (callable(UnitEnum): string)|null $label
     *
     * @throws LogicException when two enums share a short name
     */
    public static function export(array $enums, ?callable $label = null): string
    {
        $label ??= EnumTranslation::plainLabel(...);
        $names = array_map(self::shortName(...), $enums);
        $duplicates = array_keys(array_filter(array_count_values($names), static fn (int $count): bool => $count > 1));

        if ([] !== $duplicates) {
            throw new LogicException(\sprintf('Several enums are named %s; export them separately.', implode(', ', $duplicates)));
        }

        $source = "// Generated by phil/enums-bundle; do not edit.\n";

        foreach ($enums as $index => $enum) {
            $source .= "\n".self::enum($enum, $names[$index], $label);
        }

        return $source;
    }

    /**
     * @param class-string<UnitEnum>     $enum
     * @param callable(UnitEnum): string $label
     */
    private static function enum(string $enum, string $name, callable $label): string
    {
        $constants = '';
        $labels = '';

        foreach ($enum::cases() as $case) {
            $value = self::json(self::primitive($case));
            $deprecated = Reflection::isDeprecated($case) ? "  /** @deprecated */\n" : '';
            $constants .= $deprecated.'  '.$case->name.': '.$value.",\n";
            $labels .= '  '.$value.': '.self::json($label($case)).",\n";
        }

        return 'export const '.$name." = {\n".$constants."} as const;\n"
            .'export type '.$name.' = (typeof '.$name.')[keyof typeof '.$name."];\n"
            .'export const '.$name.'Labels: Record<'.$name.", string> = {\n".$labels."};\n"
            .self::declared($enum, $name);
    }

    /**
     * The descriptions, groups and default case of the enum, each only when it declares some.
     *
     * @param class-string<UnitEnum> $enum
     */
    private static function declared(string $enum, string $name): string
    {
        $parts = [];
        $descriptions = '';

        foreach ($enum::cases() as $case) {
            $description = EnumTranslation::descriptionKey($case);
            $descriptions .= null === $description ? '' : '  '.self::json(self::primitive($case)).': '.self::json($description).",\n";
        }

        if ('' !== $descriptions) {
            $parts[] = 'export const '.$name.'Descriptions: Partial<Record<'.$name.", string>> = {\n".$descriptions."};\n";
        }

        $groups = CaseCollection::of($enum::cases())->groupByMeta(Group::class);

        if ([] !== $groups) {
            $lines = array_map(
                static fn (int|string $group, CaseCollection $cases): string => '  '.self::json((string) $group).': ['.implode(', ', array_map(self::json(...), $cases->values()))."],\n",
                array_keys($groups),
                $groups,
            );
            $parts[] = 'export const '.$name.'Groups: Record<string, readonly '.$name."[]> = {\n".implode('', $lines)."};\n";
        }

        $default = Reflection::defaultCase($enum);

        if ($default instanceof UnitEnum) {
            $parts[] = 'export const '.$name.'Default: '.$name.' = '.self::json(self::primitive($default)).";\n";
        }

        return implode('', $parts);
    }

    private static function primitive(UnitEnum $case): int|string
    {
        return $case instanceof BackedEnum ? $case->value : $case->name;
    }

    /**
     * @param class-string<UnitEnum> $enum
     */
    private static function shortName(string $enum): string
    {
        $parts = explode('\\', $enum);

        return end($parts);
    }

    private static function json(int|string $value): string
    {
        return json_encode($value, \JSON_THROW_ON_ERROR | \JSON_UNESCAPED_UNICODE | \JSON_UNESCAPED_SLASHES);
    }
}
