<?php

declare(strict_types=1);

use ShipMonk\ComposerDependencyAnalyser\Config\Configuration;
use ShipMonk\ComposerDependencyAnalyser\Config\ErrorType;

/**
 * The bundle's declared dependencies, checked against the bundle installed on its own.
 *
 * The optional integrations are used by the production code but only required in development and suggested: the
 * bundle registers each only when it is installed — the ORM for the schema listener, AssetMapper for the controller,
 * phil/notifications-bundle for its preferences, phil/privacy-bundle for the export and erasure.
 */
return new Configuration()
    ->addPathToScan(__DIR__.'/src', isDev: false)
    ->addPathToScan(__DIR__.'/tests', isDev: true)
    ->ignoreErrorsOnPackages([
        'doctrine/orm',
        'phil/notifications-bundle',
        'phil/privacy-bundle',
        'symfony/asset-mapper',
    ], [ErrorType::DEV_DEPENDENCY_IN_PROD]);
