<?php

declare(strict_types=1);

namespace Phil\AiBundle\Tests\Unit\Application;

use DateTimeImmutable;
use Phil\AiBundle\Application\AiNotice;
use Phil\AiBundle\Application\AiUsageRegister;
use Phil\AiBundle\Application\AiUse;
use Phil\AiBundle\Application\Media;
use Phil\AiBundle\Application\Suggestion;
use Phil\AiBundle\Application\TaskCatalog;
use Phil\AiBundle\Application\TaskDefinition;
use Phil\AiBundle\Application\ToolDefinition;
use Phil\AiBundle\Domain\Journal\KeySource;
use Phil\AiBundle\Domain\Journal\Output;
use Phil\AiBundle\Domain\ValueObject\Cost;
use Phil\AiBundle\Domain\ValueObject\Subject;
use Phil\AiBundle\Domain\ValueObject\TaskKind;
use Phil\AiBundle\Domain\ValueObject\Tokens;
use Phil\CreationDisclosure\GenerativeAi;
use PHPUnit\Framework\Attributes\CoversClass;
use PHPUnit\Framework\TestCase;
use Symfony\Component\Translation\Loader\PhpFileLoader;
use Symfony\Component\Translation\Translator;

/**
 * What a person is told: the notices beside a model, the disclosure of what a suggestion made, and the register of the
 * application's uses of AI.
 */
#[CoversClass(AiNotice::class)]
#[CoversClass(AiUsageRegister::class)]
#[CoversClass(AiUse::class)]
#[CoversClass(Media::class)]
#[CoversClass(Suggestion::class)]
final class DisclosureTest extends TestCase
{
    public function testTheNoticesAreTranslatedInEnglishAndFrench(): void
    {
        $translator = new Translator('en');
        $translator->addLoader('php', new PhpFileLoader());

        foreach (['en', 'fr'] as $locale) {
            $translator->addResource('php', \dirname(__DIR__, 3).'/translations/phil_ai_notice.'.$locale.'.php', $locale, AiNotice::DOMAIN);
        }

        $notice = new AiNotice($translator);

        self::assertSame('You are talking to an AI. Its answers are suggestions: check them before you use them.', $notice->interaction());
        self::assertSame('Vous parlez à une IA. Ses réponses sont des suggestions : vérifiez-les avant de vous en servir.', $notice->interaction('fr'));
        self::assertSame('This text was generated by AI. Nothing is applied until you accept it.', $notice->generated(Output::Text));
        self::assertSame('This text was generated by AI. Nothing is applied until you accept it.', $notice->generated(Output::Structured, 'en'));
        self::assertSame('Cette image a été générée par une IA. Rien n’est appliqué tant que vous ne l’acceptez pas.', $notice->generated(Output::Image, 'fr'));
        self::assertSame('This audio was generated by AI. Nothing is applied until you accept it.', $notice->generated(Output::Speech));
    }

    public function testASuggestionDisclosesWhatItMade(): void
    {
        $text = $this->suggestion(Output::Text)->disclosure();

        self::assertSame(['text' => 'trainedAlgorithmicMedia'], $text->toArray());
        self::assertSame(GenerativeAi::Full, $text->generativeAi());
        self::assertSame(['text' => 'compositeWithTrainedAlgorithmicMedia'], $this->suggestion(Output::Text)->disclosure(edited: true)->toArray());
        self::assertSame(GenerativeAi::Partial, $this->suggestion(Output::Text)->disclosure(true)->generativeAi());
        self::assertSame(['text' => 'trainedAlgorithmicMedia'], $this->suggestion(Output::Structured)->disclosure()->toArray());
        self::assertSame(['image' => 'trainedAlgorithmicMedia'], $this->suggestion(Output::Image)->disclosure()->toArray());
        self::assertSame(['audio' => 'trainedAlgorithmicMedia'], $this->suggestion(Output::Speech)->disclosure()->toArray());
    }

    public function testAMediaReadsAsADataAddress(): void
    {
        self::assertSame('data:image/png;base64,UE5H', new Media('PNG', 'image/png')->toDataUri());
        self::assertSame('data:application/octet-stream;base64,TVAz', new Media('MP3')->toDataUri());
    }

    public function testTheRegisterListsEachUseOfTheConfiguration(): void
    {
        $register = new AiUsageRegister(new TaskCatalog(
            new TaskDefinition(TaskKind::fromString('rules.answer'), 'main', 'model-a', [], 1, Output::Text, null, [new ToolDefinition('look_up', 'Looks a rule up.'), new ToolDefinition('roll', 'Rolls dice.')], 'Answers a rules question.'),
            new TaskDefinition(TaskKind::fromString('cover.draw'), 'images', 'model-b', [], 1, Output::Image),
        ));

        self::assertEquals([
            new AiUse('rules.answer', 'Answers a rules question.', Output::Text, 'main', 'model-a', ['look_up', 'roll']),
            new AiUse('cover.draw', '', Output::Image, 'images', 'model-b', []),
        ], $register->uses());
        self::assertSame([], new AiUsageRegister(new TaskCatalog())->uses());
    }

    private function suggestion(Output $output): Suggestion
    {
        return new Suggestion('t-1', TaskKind::fromString('k'), Subject::fromString('s'), '', Tokens::none(), new Cost(0, 'USD'), KeySource::Application, new DateTimeImmutable(), $output);
    }
}
