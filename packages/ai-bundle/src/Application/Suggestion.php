<?php

declare(strict_types=1);

namespace Phil\AiBundle\Application;

use DateTimeImmutable;
use Phil\AiBundle\Domain\Journal\KeySource;
use Phil\AiBundle\Domain\Journal\Output;
use Phil\AiBundle\Domain\ValueObject\Cost;
use Phil\AiBundle\Domain\ValueObject\Subject;
use Phil\AiBundle\Domain\ValueObject\TaskKind;
use Phil\AiBundle\Domain\ValueObject\Tokens;
use Phil\CreationDisclosure\CreationDisclosure;
use Phil\CreationDisclosure\DigitalSourceType;
use Phil\CreationDisclosure\Part;

/**
 * What a task proposes, for a person to accept, change or set aside: nothing it says is applied, and no tool it
 * proposes to call is run, until the application does so, and tells `AiTasks` what was decided, by the suggestion's
 * identifier.
 *
 * The text, the data, the tool calls and the media live only here: the application shows them, keeps them in its
 * draft if it wants, and the journal records the decision without them.
 */
final readonly class Suggestion
{
    /**
     * @param object|array<array-key, mixed>|null $data      the structured output, for a task that asks for one
     * @param list<ProposedToolCall>              $toolCalls the tools the model proposes to call, none of them run
     */
    public function __construct(
        /** The task's identifier in the journal. */
        public string $id,
        public TaskKind $kind,
        public Subject $subject,
        public string $text,
        public Tokens $tokens,
        public Cost $cost,
        public KeySource $keySource,
        public DateTimeImmutable $proposedAt,
        public Output $output = Output::Text,
        public object|array|null $data = null,
        public array $toolCalls = [],
        public ?Media $media = null,
    ) {
    }

    /**
     * How the work that takes this suggestion was made, for `phil/creation-disclosure`: its part — text, image or
     * audio — generated by AI, or composed with what AI generated once the person changed it.
     */
    public function disclosure(bool $edited = false): CreationDisclosure
    {
        $part = match ($this->output) {
            Output::Text, Output::Structured => Part::Text,
            Output::Image => Part::Image,
            Output::Speech => Part::Audio,
        };

        return CreationDisclosure::of($part)->declare($part, $edited ? DigitalSourceType::CompositeWithTrainedAlgorithmicMedia : DigitalSourceType::TrainedAlgorithmicMedia);
    }
}
