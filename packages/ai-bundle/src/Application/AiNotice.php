<?php

declare(strict_types=1);

namespace Phil\AiBundle\Application;

use Phil\AiBundle\Domain\Journal\Output;
use Symfony\Contracts\Translation\TranslatorInterface;

/**
 * The notices a person is owed beside a model: that they are talking to an AI, and that what they see was generated
 * by one. The messages are those of the domain `phil_ai_notice`, shipped in English and French, which an application
 * overrides in its own translations.
 */
final readonly class AiNotice
{
    public const string DOMAIN = 'phil_ai_notice';

    public function __construct(
        private TranslatorInterface $translator,
    ) {
    }

    /**
     * "You are talking to an AI.": beside a conversation or an assistant, before the first exchange.
     */
    public function interaction(?string $locale = null): string
    {
        return $this->translator->trans('interaction', [], self::DOMAIN, $locale);
    }

    /**
     * That the text, the image or the speech shown was generated by AI, and stays a proposal until the person decides.
     */
    public function generated(Output $output, ?string $locale = null): string
    {
        return $this->translator->trans('generated.'.(Output::Structured === $output ? Output::Text->value : $output->value), [], self::DOMAIN, $locale);
    }
}
